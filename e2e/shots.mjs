// Design review screenshots (desktop + mobile) against e2e/server.mjs. Usage: node e2e/shots.mjs [outDir]
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium, devices } = require('playwright');
const BASE = 'http://localhost:8799';
const OUT = process.argv[2] || new URL('./artifacts/design/', import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });
const b = await chromium.launch();
let ipn = Number(process.argv[3] || Math.floor(Math.random() * 200));
for (const [label, opts] of [['d', { viewport: { width: 1440, height: 900 } }], ['m', { ...devices['iPhone 13'] }]]) {
  const ctx = await b.newContext(opts);
  await ctx.setExtraHTTPHeaders({ 'x-test-ip': `198.51.101.${ipn++ % 250}` });
  await ctx.route('https://www.youtube.com/**', (r) => r.fulfill({ status: 200, contentType: 'text/html', body: '<body style="background:#000"></body>' }));
  const p = await ctx.newPage();
  const shot = (n, full = true) => p.screenshot({ path: join(OUT, `${label}-${n}.png`), fullPage: full });
  await p.goto(BASE + '/', { waitUntil: 'networkidle' });
  await shot('01-home');
  await p.fill('#video-url', 'https://www.youtube.com/watch?v=dQw4w9WgXcQ');
  await p.locator('form button[type="submit"]').first().click();
  await p.getByRole('button', { name: /Make my revision pack/ }).waitFor();
  await p.waitForTimeout(900);
  await p.getByRole('button', { name: /Make my revision pack/ }).scrollIntoViewIfNeeded();
  await shot('02-transcript', false);
  await p.getByRole('button', { name: /Make my revision pack/ }).click();
  await p.getByText(/note points ·/).first().waitFor();
  await p.waitForTimeout(600);
  await p.getByText(/note points ·/).first().scrollIntoViewIfNeeded();
  await shot('03-pack-notes', false);
  await p.getByRole('button', { name: /From lecture · / }).first().click();
  await p.getByRole('button', { name: /Flashcards/ }).first().click();
  await p.getByRole('button', { name: /Reveal Answer/ }).click();
  await p.getByRole('button', { name: /Reveal|Show Question/ }).scrollIntoViewIfNeeded();
  await shot('04-flashcard', false);
  await p.getByRole('button', { name: /^Good/ }).first().click();
  await p.getByRole('button', { name: /Quiz/ }).first().click();
  await p.locator('button[dir="auto"]:not([disabled])').first().click();
  await shot('05-quiz', false);
  await p.goto(BASE + '/study', { waitUntil: 'networkidle' });
  await p.waitForTimeout(400);
  await shot('06-study');
  await p.goto(BASE + '/pricing', { waitUntil: 'networkidle' });
  await shot('07-pricing');
  await p.goto(BASE + '/terms', { waitUntil: 'networkidle' });
  await shot('08-terms', false);
  await p.goto(BASE + '/guide', { waitUntil: 'networkidle' });
  await shot('09-guide');
  await ctx.close();
}
await b.close();
